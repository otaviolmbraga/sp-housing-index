"""
Build the data artifacts for the public sp-housing-index site.

Run with the Anaconda interpreter:
    C:/Users/otavi/anaconda3/python.exe _build/make_site_data.py

Produces:
  (1) ../data.js         -- the tiny index series embedded as window.CS_DATA
                            (loaded by index.html; works over file:// and GitHub Pages)
  (2) ../_release_assets/itbi_compilado.csv.gz
                            -- gzip of the 849 MB transaction CSV, for upload as a
                            GitHub *Release* asset (NOT committed to the repo).

Nothing here modifies the source files under Dropbox/sp_housing.
"""
import csv
import gzip
import json
import shutil
from pathlib import Path

SRC_DIR = Path(r"C:/Users/otavi/Dropbox/sp_housing")
SITE_DIR = Path(__file__).resolve().parent.parent          # sp-housing-index/
INDEX_CSV = SRC_DIR / "data" / "clean_data" / "cs_index_final.csv"
ITBI_CSV = SRC_DIR / "data" / "clean_data" / "itbi_compilado.csv"

DATA_JS = SITE_DIR / "data.js"
REL_DIR = SITE_DIR / "_release_assets"
ITBI_GZ = REL_DIR / "itbi_compilado.csv.gz"

# columns we surface in the interactive chart
SERIES = ["cs_sp", "ipca", "cdi", "fipezap", "ibovespa"]
YOY = [s + "_yoy" for s in SERIES]


def build_index_js():
    rows = []
    with INDEX_CSV.open(newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            rec = {"date": r["date"][:7]}  # YYYY-MM
            for c in SERIES + YOY:
                v = r.get(c, "")
                rec[c] = round(float(v), 6) if v not in ("", None) else None
            rows.append(rec)
    payload = {
        "series": SERIES,
        "base": rows[0]["date"] if rows else None,
        "rows": rows,
    }
    js = "// AUTO-GENERATED by _build/make_site_data.py -- do not edit by hand\n"
    js += "window.CS_DATA = " + json.dumps(payload, separators=(",", ":")) + ";\n"
    DATA_JS.write_text(js, encoding="utf-8")
    print(f"wrote {DATA_JS}  ({DATA_JS.stat().st_size/1024:.1f} KB, {len(rows)} months)")


def build_itbi_gz():
    if not ITBI_CSV.exists():
        print(f"!! source not found, skipping gzip: {ITBI_CSV}")
        return
    REL_DIR.mkdir(parents=True, exist_ok=True)
    src_mb = ITBI_CSV.stat().st_size / 1e6
    print(f"gzipping {ITBI_CSV.name} ({src_mb:.0f} MB)  ->  {ITBI_GZ.name} ...")
    with ITBI_CSV.open("rb") as fin, gzip.open(ITBI_GZ, "wb", compresslevel=6) as fout:
        shutil.copyfileobj(fin, fout, length=16 * 1024 * 1024)
    out_mb = ITBI_GZ.stat().st_size / 1e6
    print(f"wrote {ITBI_GZ}  ({out_mb:.0f} MB, {out_mb/src_mb*100:.0f}% of original)")
    if out_mb >= 1000:
        print("!! WARNING: gz exceeds 1 GB")
    elif out_mb >= 2000:
        print("!! WARNING: gz exceeds GitHub 2 GB per-asset Release limit")


if __name__ == "__main__":
    build_index_js()
    build_itbi_gz()
    print("done.")
